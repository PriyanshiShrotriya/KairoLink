CREATE TABLE round_trip_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    outbound_booking_id BIGINT NOT NULL,
    requested_return_date DATE NOT NULL,
    requested_return_time TIME NOT NULL,
    return_pickup VARCHAR(150) NOT NULL,
    return_destination VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL,
    passenger_message VARCHAR(1000),
    driver_response VARCHAR(1000),
    confirmed_return_ride_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_round_trip_requests PRIMARY KEY (id),
    CONSTRAINT fk_round_trip_requests_outbound_booking
        FOREIGN KEY (outbound_booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT fk_round_trip_requests_return_ride
        FOREIGN KEY (confirmed_return_ride_id) REFERENCES rides (id) ON DELETE SET NULL,
    CONSTRAINT ck_round_trip_requests_status
        CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_round_trip_requests_different_locations
        CHECK (return_pickup <> return_destination)
);

CREATE INDEX idx_round_trip_requests_booking
    ON round_trip_requests (outbound_booking_id);

CREATE INDEX idx_round_trip_requests_status
    ON round_trip_requests (status);

CREATE INDEX uk_round_trip_requests_active_booking
    ON round_trip_requests (outbound_booking_id)
